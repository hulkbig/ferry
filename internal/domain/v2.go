// LogicalModel is the stable model contract exposed to clients. Its ID is the
// value accepted by the standard protocol model field.
type LogicalModel struct {
	ID            string `json:"id"`
	DisplayName   string `json:"display_name,omitempty"`
	Description   string `json:"description,omitempty"`
	AutoGenerated bool   `json:"auto_generated,omitempty"`
	Enabled       bool   `json:"enabled"`
	// ExactOnly rejects semantically equivalent mappings as well as lossy
	// conversions. The zero value preserves the upgrade-compatible policy of
	// allowing registered CompatMapped behavior.
	ExactOnly bool `json:"exact_only,omitempty"`
	// FirstOutputTimeoutSeconds bounds each admitted attempt until its first
	// effective text, reasoning, or tool output. Zero disables this timeout;
	// output already in progress is not subject to it.
	FirstOutputTimeoutSeconds    int                          `json:"first_output_timeout_seconds,omitempty"`
	ExistingConversationStrategy ExistingConversationStrategy `json:"existing_conversation_strategy,omitempty"`
	DefaultRoute                 RouteSpec                    `json:"default_route"`
	Overrides                    []OverrideSpec               `json:"overrides,omitempty"`
}

// ExistingConversationStrategy controls only conversations that predate a
// route revision. In-flight requests are always pinned to the immutable
// snapshot they entered with.
type ExistingConversationStrategy string

const (
	ConversationKeepExisting ExistingConversationStrategy = "keep-existing"
	ConversationMigrate      ExistingConversationStrategy = "migrate"
)

func (s ExistingConversationStrategy) Valid() bool {
	return s == "" || s == ConversationKeepExisting || s == ConversationMigrate
}

type ProviderType string

const (
	ProviderCustom        ProviderType = "custom"
	ProviderCliproxyCodex ProviderType = "cliproxy-codex"
)

// ProviderModelSyncInterval controls how often Ferry refreshes a
// Provider's catalog-only, non-inference model listing. The empty value stays
// valid on older persisted revisions and deliberately means one hour, so an
// upgrade enables discovery without rewriting configuration history.
type ProviderModelSyncInterval string

const (
	ProviderModelSyncOff       ProviderModelSyncInterval = "off"
	ProviderModelSync30Minutes ProviderModelSyncInterval = "30m"
	ProviderModelSync1Hour     ProviderModelSyncInterval = "1h"
)

func (i ProviderModelSyncInterval) Valid() bool {
	return i == "" || i == ProviderModelSyncOff || i == ProviderModelSync30Minutes || i == ProviderModelSync1Hour
}

func (i ProviderModelSyncInterval) Effective() ProviderModelSyncInterval {
	if i == "" {
		return ProviderModelSync1Hour
	}
	return i
}

func (i ProviderModelSyncInterval) Duration() time.Duration {
	switch i.Effective() {
	case ProviderModelSync30Minutes:
		return 30 * time.Minute
	case ProviderModelSync1Hour:
		return time.Hour
	default:
		return 0
	}
}

