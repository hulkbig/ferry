// Provider is the only upstream resource boundary a route may reference.
// BaseURL is the shared default; protocol-scoped connections may override it
// alongside their credentials and native model supply.
type Provider struct {
	ID                 string                    `json:"id"`
	Name               string                    `json:"name"`
	Type               ProviderType              `json:"type"`
	BaseURL            string                    `json:"base_url,omitempty"`
	Enabled            bool                      `json:"enabled"`
	ModelSyncInterval  ProviderModelSyncInterval `json:"model_sync_interval,omitempty"`
	ModelSyncCatalog   *ProviderModelSyncCatalog `json:"model_sync_catalog,omitempty"`
	ProtocolConversion map[Protocol]bool         `json:"protocol_conversion,omitempty"`
	// ScheduledMessage sends one provider-scoped canonical user message every
	// five hours. The configured upstream model is explicit so a catalog
	// reorder can never silently redirect this background traffic.
	ScheduledMessage *ProviderScheduledMessage `json:"scheduled_message,omitempty"`
	// Concurrency overrides the runtime admission defaults for every
	// Connection in this Provider. A Connection-level policy, when present,
	// remains the more specific override.
	Concurrency *ConcurrencyPolicy `json:"concurrency,omitempty"`
	Connections []ConnectionRef    `json:"connections,omitempty"`
}

const ProviderScheduledMessageMaxBytes = 16 * 1024

// ProviderScheduledMessage is the per-Provider configuration for the fixed
// five-hour background message. Only text-capable upstream models are valid;
// Images endpoints remain native image operations rather than being treated
// as a text-message transport.
type ProviderScheduledMessage struct {
	Enabled       bool   `json:"enabled"`
	UpstreamModel string `json:"upstream_model"`
	Message       string `json:"message"`
}

// AllowsProtocolConversion reports whether requests arriving through p may be
// converted to a model's native upstream protocol. A nil map preserves the
// historical all-protocol behavior for configurations created before this
// control was exposed; an explicit false value disables conversion for p.
func (p *Provider) AllowsProtocolConversion(protocol Protocol) bool {
	if p != nil && p.Type == ProviderCliproxyCodex {
		// Codex text models use Responses while image-only models use the
		// Images API. Chat Completions and Anthropic ingress are deliberately
		// served through Ferry's canonical text conversion layer.
		return protocol == ProtocolOpenAIResponses || protocol == ProtocolOpenAIChat || protocol == ProtocolAnthropic
	}
	return p == nil || p.ProtocolConversion == nil || p.ProtocolConversion[protocol]
}

// EffectiveProtocolConversion returns the runtime policy. Codex OAuth text
// models speak Responses upstream while Ferry owns Chat Completions and
// Anthropic translation, independent of stale or hand-edited flags. Images
// remain native-only and therefore need no conversion flag.
func (p *Provider) EffectiveProtocolConversion() map[Protocol]bool {
	if p != nil && p.Type == ProviderCliproxyCodex {
		return map[Protocol]bool{
			ProtocolOpenAIResponses: true,
			ProtocolOpenAIChat:      true,
			ProtocolAnthropic:       true,
		}
	}
	if p == nil || p.ProtocolConversion == nil {
		return nil
	}
	out := make(map[Protocol]bool, len(p.ProtocolConversion))
	for protocol, enabled := range p.ProtocolConversion {
		out[protocol] = enabled
	}
	return out
}

type ConnectionRef struct {
	ID string `json:"id"`
}

// Connection is one executable identity inside a Provider. Route contracts
// never contain this ID.
type Connection struct {
	// RuntimeID identifies this incarnation across edits/restarts. It is assigned
	// by the control plane, never derived from the operator's display name.
	RuntimeID string `json:"runtime_id,omitempty"`
	// RuntimeCredential identifies the resolved account/key without persisting it.
	RuntimeCredential string `json:"-"`
	ID                string `json:"id"`
	ProviderID        string `json:"provider_id"`
	Identity          string `json:"identity,omitempty"`
	BaseURL           string `json:"base_url,omitempty"`
	// FullURL bypasses protocol path derivation for endpoints whose request URL
	// cannot be represented as BaseURL + the standard protocol suffix. It is a
	// Connection override and is mutually exclusive with BaseURL.
	FullURL    string        `json:"full_url,omitempty"`
	Credential CredentialRef `json:"credential"`
	Enabled    bool          `json:"enabled"`
	// PlanID is the connection-level billing default: every model of this
	// connection bills under it unless the ConnectionModel names its own
	// plan_id. It mirrors the legacy channel-level plan inheritance.
	PlanID string            `json:"plan_id,omitempty"`
	Models []ConnectionModel `json:"models"`
	// Concurrency bounds simultaneous upstream attempts on this account and
	// decides what happens when the upstream throttles. Nil inherits the
	// Provider policy, then the runtime admission defaults.
	Concurrency *ConcurrencyPolicy `json:"concurrency,omitempty"`
}

// ConcurrencyPolicy is the per-connection admission contract. Local overflow
// and upstream throttling each choose strict FIFO wait or immediate failure;
// queued requests share the same bounded queue and deadline.
type ConcurrencyPolicy struct {
	// MaxConcurrent caps simultaneous upstream attempts. 0 means unlimited,
	// in which case the queue only ever engages while throttled.
	MaxConcurrent int `json:"max_concurrent,omitempty"`
	// MaxQueue bounds waiters so a stalled upstream cannot grow the queue
	// without limit. 0 selects the default.
	MaxQueue int `json:"max_queue,omitempty"`
	// MaxWaitSeconds bounds how long one request may block before it is
	// rejected. 0 selects the default.
	MaxWaitSeconds int `json:"max_wait_seconds,omitempty"`
	// QueueWhenFull controls local concurrency overflow. Nil defaults to true
	// for backward compatibility. False rejects immediately with a typed rate
	// limit failure instead of entering the FIFO admission queue.
	QueueWhenFull *bool `json:"queue_when_full,omitempty"`
	// QueueOnThrottle keeps throttled requests queued and drains them one at a
	// time. Nil defaults to true: an upstream rate limit should slow the
	// connection down, not fail the request outright.
	QueueOnThrottle *bool `json:"queue_on_throttle,omitempty"`
}

const (
	defaultAdmissionMaxQueue = 256
	defaultAdmissionMaxWait  = 2 * time.Minute
	// admissionMaxWaitCeiling stops a configuration from pinning a client
	// connection open indefinitely behind a wedged upstream.
	admissionMaxWaitCeiling = 30 * time.Minute
)

// EffectiveMaxQueue returns the configured waiter cap or the default.
func (p *ConcurrencyPolicy) EffectiveMaxQueue() int {
	if p == nil || p.MaxQueue <= 0 {
		return defaultAdmissionMaxQueue
	}
	return p.MaxQueue
}

// EffectiveMaxWait returns the configured queue deadline or the default.
func (p *ConcurrencyPolicy) EffectiveMaxWait() time.Duration {
	if p == nil || p.MaxWaitSeconds <= 0 {
		return defaultAdmissionMaxWait
	}
	if wait := time.Duration(p.MaxWaitSeconds) * time.Second; wait < admissionMaxWaitCeiling {
		return wait
	}
	return admissionMaxWaitCeiling
}

// QueuesOnThrottle reports whether a throttled connection queues instead of
// failing. Unset means yes.
func (p *ConcurrencyPolicy) QueuesOnThrottle() bool {
	return p == nil || p.QueueOnThrottle == nil || *p.QueueOnThrottle
}

// QueuesWhenFull reports whether a request waits when the local concurrency
// ceiling (or an active throttle cooldown) has no immediately available slot.
// Unset preserves the historical FIFO behavior.
func (p *ConcurrencyPolicy) QueuesWhenFull() bool {
	return p == nil || p.QueueWhenFull == nil || *p.QueueWhenFull
}

// Limit returns the configured simultaneous-attempt cap, 0 meaning unlimited.
func (p *ConcurrencyPolicy) Limit() int {
	if p == nil || p.MaxConcurrent < 0 {
		return 0
	}
	return p.MaxConcurrent
}

// Validate rejects nonsensical admission settings at config time.
func (p *ConcurrencyPolicy) Validate() error {
	if p == nil {
		return nil
	}
	if p.MaxConcurrent < 0 {
		return fmt.Errorf("concurrency.max_concurrent must not be negative")
	}
	if p.MaxQueue < 0 {
		return fmt.Errorf("concurrency.max_queue must not be negative")
	}
	if p.MaxWaitSeconds < 0 {
		return fmt.Errorf("concurrency.max_wait_seconds must not be negative")
	}
	if p.MaxWaitSeconds > int(admissionMaxWaitCeiling/time.Second) {
		return fmt.Errorf("concurrency.max_wait_seconds must not exceed %d", int(admissionMaxWaitCeiling/time.Second))
	}
	return nil
}

// ConnectionModel is one supply fact. ExecutionTargetID links the V2 product
// projection to the existing ResourceTarget runtime leaf and is never exposed
// as part of the V2 product contract.
type ConnectionModel struct {
	UpstreamModel     string           `json:"upstream_model"`
	Protocols         []Protocol       `json:"protocols"`
	Capabilities      Capabilities     `json:"capabilities"`
	PlanID            string           `json:"plan_id,omitempty"`
	ExecutionTargetID ResourceTargetID `json:"-"`
}

// ProviderModel is the union view of an upstream model supplied by a
// provider's connections.
type ProviderModel struct {
	ProviderID           string       `json:"provider_id"`
	UpstreamModel        string       `json:"upstream_model"`
	SupportedConnections []string     `json:"supported_connections"`
	EligibleConnections  []string     `json:"eligible_connections"`
	Capabilities         Capabilities `json:"capabilities"`
}

// ProviderModelKey is the internal stable lookup key. It is not an API ID.
func ProviderModelKey(providerID, upstreamModel string) string {
	return providerID + "\x00" + upstreamModel
}

// V2ExecutionTargetID deterministically names the private runtime leaf for a
// Connection×UpstreamModel supply fact. Product APIs expose the provider,
// connection and model fields separately and never expose this opaque ID.
func V2ExecutionTargetID(providerID, connectionID, upstreamModel string) ResourceTargetID {
	sum := sha256.Sum256([]byte(ProviderModelKey(providerID, connectionID+"\x00"+upstreamModel)))
	return ResourceTargetID("v2-" + hex.EncodeToString(sum[:12]))
}

// RuntimeIdentity binds cached availability to an incarnation and credential.
// Display identity, enablement and concurrency edits do not change ownership.
func (c *Connection) RuntimeIdentity() string {
	parts := []string{c.ProviderID, c.ID, c.RuntimeID, c.BaseURL, c.FullURL,
		c.Credential.SecretRef, c.Credential.Header, c.Credential.QueryParam, c.Credential.Prefix, c.RuntimeCredential}
	sum := sha256.Sum256([]byte(strings.Join(parts, "\x00")))
	return hex.EncodeToString(sum[:])
}

func (c *Connection) RuntimeTargetID(model string) ResourceTargetID {
	if c.RuntimeID == "" && c.RuntimeCredential == "" {
		return V2ExecutionTargetID(c.ProviderID, c.ID, model)
	}
	return V2ExecutionTargetID(c.ProviderID, c.RuntimeIdentity(), model)
}

// RouteStep deliberately has no ConnectionID, weight or priority. Slice order
// in RouteSpec is the deterministic route priority.
type RouteStep struct {
	ProviderID    string        `json:"provider_id"`
	UpstreamModel string        `json:"upstream_model"`
	RecoverOn     []FailureType `json:"recover_on"`
}

type RouteSpec struct {
	Steps []RouteStep `json:"steps"`
}

