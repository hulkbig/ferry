func TestValidateV2DomainEnsuresExactSameNameLogicalModels(t *testing.T) {
	f := &File{
		V2DomainSource: V2DomainSourceNative,
		Providers: []domain.Provider{
			{ID: "disabled", Type: domain.ProviderCustom, BaseURL: "https://disabled.test", Connections: []domain.ConnectionRef{{ID: "disabled-account"}}},
			{ID: "enabled", Type: domain.ProviderCustom, BaseURL: "https://enabled.test", Enabled: true, Connections: []domain.ConnectionRef{{ID: "enabled-account"}}},
		},
		Connections: []domain.Connection{
			{ID: "disabled-account", ProviderID: "disabled", Models: []domain.ConnectionModel{{UpstreamModel: "shared-model", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}}}},
			{ID: "enabled-account", ProviderID: "enabled", Enabled: true, Models: []domain.ConnectionModel{
				{UpstreamModel: "shared-model", Protocols: []domain.Protocol{domain.ProtocolOpenAIResponses}},
				{UpstreamModel: "google/gemini-3.7-flash", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}},
			}},
		},
		LogicalModels: []domain.LogicalModel{{
			ID: "smart", Enabled: true,
			DefaultRoute: domain.RouteSpec{Steps: []domain.RouteStep{{ProviderID: "enabled", UpstreamModel: "shared-model"}}},
		}},
	}
	if err := ValidateV2Domain(f); err != nil {
		t.Fatal(err)
	}
	if len(f.LogicalModels) != 3 {
		t.Fatalf("same-name logical models=%+v", f.LogicalModels)
	}
	byID := map[string]domain.LogicalModel{}
	for _, logical := range f.LogicalModels {
		byID[logical.ID] = logical
	}
	for _, id := range []string{"shared-model", "google/gemini-3.7-flash"} {
		logical, ok := byID[id]
		if !ok || !logical.AutoGenerated || !logical.Enabled || logical.DisplayName != id || len(logical.DefaultRoute.Steps) != 1 ||
			logical.DefaultRoute.Steps[0].ProviderID != "enabled" || logical.DefaultRoute.Steps[0].UpstreamModel != id {
			t.Fatalf("same-name logical model %q=%+v", id, logical)
		}
	}
	if created := EnsureSameNameLogicalModels(f); len(created) != 0 || len(f.LogicalModels) != 3 {
		t.Fatalf("same-name reconciliation was not idempotent: created=%v models=%+v", created, f.LogicalModels)
	}
	f.Connections[1].Models = f.Connections[1].Models[:1]
	EnsureSameNameLogicalModels(f)
	if len(f.LogicalModels) != 2 {
		t.Fatalf("removed upstream model retained its generated logical model: %+v", f.LogicalModels)
	}
}

