func TestValidateV2OverrideMatchAndOrdering(t *testing.T) {
	valid := func() *File {
		return &File{
			V2DomainSource: V2DomainSourceNative,
			Providers: []domain.Provider{{
				ID: "provider", Type: domain.ProviderCustom, BaseURL: "https://provider.test", Enabled: true,
				Connections: []domain.ConnectionRef{{ID: "connection"}},
			}},
			Connections: []domain.Connection{{
				ID: "connection", ProviderID: "provider", Enabled: true,
				Models: []domain.ConnectionModel{
					{UpstreamModel: "primary", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}},
					{UpstreamModel: "fallback", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}},
				},
			}},
			LogicalModels: []domain.LogicalModel{{
				ID: "smart", Enabled: true, DefaultRoute: domain.RouteSpec{Steps: []domain.RouteStep{
					{ProviderID: "provider", UpstreamModel: "primary"},
					{ProviderID: "provider", UpstreamModel: "fallback"},
				}},
				Overrides: []domain.OverrideSpec{{
					ID: "business-hours", Enabled: true, Mode: domain.OverrideCustomRoute,
					Callers: []string{"team"}, Protocols: []domain.Protocol{domain.ProtocolOpenAIChat},
					Weekdays: []string{"mon", "tue"}, Timezone: "Asia/Shanghai",
					Window: &domain.TimeWindow{Start: "09:00", End: "18:00"},
					Route:  &domain.RouteSpec{Steps: []domain.RouteStep{{ProviderID: "provider", UpstreamModel: "fallback"}}},
				}},
			}},
		}
	}
	if err := ValidateV2Domain(valid()); err != nil {
		t.Fatalf("valid override rejected: %v", err)
	}

	for _, test := range []struct {
		name   string
		mutate func(*domain.OverrideSpec)
		want   string
	}{
		{"invalid window", func(o *domain.OverrideSpec) { o.Window.Start = "25:00" }, "invalid time window"},
		{"empty window", func(o *domain.OverrideSpec) { o.Window.End = o.Window.Start }, "must be non-empty"},
		{"invalid timezone", func(o *domain.OverrideSpec) { o.Timezone = "Mars/Olympus" }, "invalid timezone"},
		{"invalid weekday", func(o *domain.OverrideSpec) { o.Weekdays = []string{"funday"} }, "invalid weekday"},
		{"untrimmed caller", func(o *domain.OverrideSpec) { o.Callers = []string{" team "} }, "trimmed"},
		{"duplicate protocol", func(o *domain.OverrideSpec) {
			o.Protocols = []domain.Protocol{domain.ProtocolOpenAIChat, domain.ProtocolOpenAIChat}
		}, "protocols must be valid and unique"},
	} {
		t.Run(test.name, func(t *testing.T) {
			file := valid()
			test.mutate(&file.LogicalModels[0].Overrides[0])
			if err := ValidateV2Domain(file); err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("validation error = %v, want %q", err, test.want)
			}
		})
	}

	recoveryFile := valid()
	recoveryFile.LogicalModels[0].DefaultRoute.Steps[0].RecoverOn = []domain.FailureType{domain.FailConnect, domain.FailConnect}
	if err := ValidateV2Domain(recoveryFile); err == nil || !strings.Contains(err.Error(), "recover_on values must be unique") {
		t.Fatalf("duplicate recovery validation error = %v", err)
	}
	recoveryFile = valid()
	recoveryFile.LogicalModels[0].DefaultRoute.Steps[1].RecoverOn = []domain.FailureType{domain.FailConnect}
	if err := ValidateV2Domain(recoveryFile); err != nil {
		t.Fatalf("known final recovery should be normalized for compatibility: %v", err)
	}
	if recoveryFile.LogicalModels[0].DefaultRoute.Steps[1].RecoverOn != nil {
		t.Fatalf("final recovery was not normalized: %+v", recoveryFile.LogicalModels[0].DefaultRoute.Steps[1])
	}
	recoveryFile = valid()
	recoveryFile.LogicalModels[0].DefaultRoute.Steps[1].RecoverOn = []domain.FailureType{"made-up"}
	if err := ValidateV2Domain(recoveryFile); err == nil || !strings.Contains(err.Error(), "unknown recover_on") {
		t.Fatalf("unknown final recovery validation error = %v", err)
	}

	file := valid()
	duplicate := file.LogicalModels[0].Overrides[0]
	duplicate.ID = "duplicate"
	file.LogicalModels[0].Overrides = append(file.LogicalModels[0].Overrides, duplicate)
	if err := ValidateV2Domain(file); err == nil || !strings.Contains(err.Error(), "duplicates the match conditions") {
		t.Fatalf("duplicate match validation error = %v", err)
	}

	file = valid()
	catchAll := file.LogicalModels[0].Overrides[0]
	catchAll.ID = "catch-all"
	catchAll.Callers, catchAll.Protocols, catchAll.Weekdays, catchAll.Window = nil, nil, nil, nil
	file.LogicalModels[0].Overrides = append([]domain.OverrideSpec{catchAll}, file.LogicalModels[0].Overrides...)
	if err := ValidateV2Domain(file); err == nil || !strings.Contains(err.Error(), "follows a catch-all") {
		t.Fatalf("shadowed match validation error = %v", err)
	}

	file = valid()
	broader := file.LogicalModels[0].Overrides[0]
	broader.ID = "broader"
	broader.Callers = []string{"team", "other-team"}
	narrower := file.LogicalModels[0].Overrides[0]
	narrower.ID = "narrower"
	narrower.Required.Tools = true
	file.LogicalModels[0].Overrides = []domain.OverrideSpec{broader, narrower}
	if err := ValidateV2Domain(file); err == nil || !strings.Contains(err.Error(), "shadowed by broader earlier override") {
		t.Fatalf("broader match validation error = %v", err)
	}

	file = valid()
	broader = file.LogicalModels[0].Overrides[0]
	broader.ID = "broader-window"
	broader.Window = &domain.TimeWindow{Start: "09:00", End: "18:00"}
	narrower = file.LogicalModels[0].Overrides[0]
	narrower.ID = "narrower-window"
	narrower.Window = &domain.TimeWindow{Start: "10:00", End: "12:00"}
	file.LogicalModels[0].Overrides = []domain.OverrideSpec{broader, narrower}
	if err := ValidateV2Domain(file); err == nil || !strings.Contains(err.Error(), "shadowed by broader earlier override") {
		t.Fatalf("containing time-window validation error = %v", err)
	}
}

