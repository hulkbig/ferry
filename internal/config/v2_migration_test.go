func TestEnsureSameNameLogicalModelsSkipsOversizedProviders(t *testing.T) {
	bulk := make([]domain.ConnectionModel, 0, 12)
	for i := 0; i < 12; i++ {
		bulk = append(bulk, domain.ConnectionModel{
			UpstreamModel: fmt.Sprintf("openrouter/model-%02d", i),
			Protocols:     []domain.Protocol{domain.ProtocolOpenAIChat},
		})
	}
	f := &File{
		V2DomainSource: V2DomainSourceNative,
		Providers: []domain.Provider{
			{ID: "bulk", Type: domain.ProviderCustom, BaseURL: "https://openrouter.ai/api/v1", Enabled: true, Connections: []domain.ConnectionRef{{ID: "bulk-conn"}}},
			{ID: "small", Type: domain.ProviderCustom, BaseURL: "https://small.test", Enabled: true, Connections: []domain.ConnectionRef{{ID: "small-conn"}}},
		},
		Connections: []domain.Connection{
			{ID: "bulk-conn", ProviderID: "bulk", Enabled: true, Models: bulk},
			{ID: "small-conn", ProviderID: "small", Enabled: true, Models: []domain.ConnectionModel{
				{UpstreamModel: "small/model-a", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}},
				{UpstreamModel: "small/model-b", Protocols: []domain.Protocol{domain.ProtocolOpenAIChat}},
			}},
		},
	}
	created := EnsureSameNameLogicalModels(f)
	if len(f.LogicalModels) != 2 {
		t.Fatalf("oversized provider must not flood the model list: %+v", f.LogicalModels)
	}
	for _, logical := range f.LogicalModels {
		if logical.DefaultRoute.Steps[0].ProviderID != "small" {
			t.Fatalf("unexpected logical model from oversized provider: %+v", logical)
		}
	}
	if len(created) != 2 {
		t.Fatalf("created = %v, want the two small-provider models", created)
	}
	// Idempotent: re-running keeps skipping the oversized provider.
	if created := EnsureSameNameLogicalModels(f); len(created) != 0 || len(f.LogicalModels) != 2 {
		t.Fatalf("reconciliation not idempotent: created=%v models=%+v", created, f.LogicalModels)
	}
	// Promoting one oversized model manually must not auto-list the rest.
	f.LogicalModels = append(f.LogicalModels, domain.LogicalModel{
		ID: "openrouter/model-00", DisplayName: "openrouter/model-00", Enabled: true,
		DefaultRoute: domain.RouteSpec{Steps: []domain.RouteStep{{ProviderID: "bulk", UpstreamModel: "openrouter/model-00"}}},
	})
	if created := EnsureSameNameLogicalModels(f); len(created) != 0 || len(f.LogicalModels) != 3 {
		t.Fatalf("manual promotion must not trigger the remaining oversized models: created=%v models=%+v", created, f.LogicalModels)
	}
	// Crossing the old missing-count threshold must not promote the remainder.
	f.LogicalModels = append(f.LogicalModels, domain.LogicalModel{ID: "openrouter/model-01", Enabled: true})
	if created := EnsureSameNameLogicalModels(f); len(created) != 0 {
		t.Fatalf("partial manual selection auto-created %v", created)
	}
	limit := 12
	f.AutoLogicalModelLimit = &limit
	if created := EnsureSameNameLogicalModels(f); len(created) != 10 {
		t.Fatalf("configured total limit should admit the remaining 10, got %v", created)
	}
	limit = 0
	f.Connections[1].Models = append(f.Connections[1].Models, domain.ConnectionModel{UpstreamModel: "small/new"})
	if created := EnsureSameNameLogicalModels(f); len(created) != 1 || created[0] != "small/new" || len(f.LogicalModels) != 15 {
		t.Fatalf("zero limit must only restrict aggregators: %v", created)
	}
}

