package management

import "net/http"

// legacyRoutesForTest keeps unit coverage for the retired implementation
// without making any legacy product route reachable from Server.Routes.
func (s *Server) legacyRoutesForTest() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /api/state", s.handleState)
	mux.HandleFunc("GET /api/dashboard", s.handleDashboard)
	mux.HandleFunc("GET /api/requests", s.handleRequests)
	mux.HandleFunc("GET /api/requests/{id}", s.handleRequestDetail)
	mux.HandleFunc("GET /api/targets/{id}/usage", s.handleTargetUsage)
	mux.HandleFunc("GET /api/consumers", s.handleConsumers)
	mux.HandleFunc("POST /api/consumers", s.handleConsumerCreate)
	mux.HandleFunc("GET /api/consumers/{name}/key", s.handleConsumerKeyReveal)
	mux.HandleFunc("GET /api/consumers/{name}/analytics", s.handleConsumerAnalytics)
	mux.HandleFunc("POST /api/consumers/{name}/rotate", s.handleConsumerRotate)
	mux.HandleFunc("PATCH /api/consumers/{name}", s.handleConsumerUpdate)
	mux.HandleFunc("DELETE /api/consumers/{name}", s.handleConsumerDelete)
	mux.HandleFunc("GET /api/policy/versions", s.handlePolicyVersions)
	mux.HandleFunc("GET /api/policies", s.handleRoutingPoliciesList)
	mux.HandleFunc("POST /api/policies", s.handleRoutingPolicyCreate)
	mux.HandleFunc("POST /api/policies/reorder", s.handleRoutingPoliciesReorder)
	mux.HandleFunc("GET /api/policies/{id}", s.handleRoutingPolicyDetail)
	mux.HandleFunc("PATCH /api/policies/{id}", s.handleRoutingPolicyUpdate)
	mux.HandleFunc("DELETE /api/policies/{id}", s.handleRoutingPolicyDelete)
	mux.HandleFunc("PATCH /api/policies/{id}/enabled", s.handleRoutingPolicyEnabled)
	mux.HandleFunc("GET /api/policies/{id}/revisions", s.handleRoutingPolicyRevisions)
	mux.HandleFunc("POST /api/policies/{id}/rollback", s.handleRoutingPolicyRollback)
	mux.HandleFunc("GET /api/config", s.handleConfig)
	mux.HandleFunc("GET /api/config/raw", s.handleConfigRaw)
	mux.HandleFunc("POST /api/policy/validate", s.handleValidate)
	mux.HandleFunc("POST /api/policy/dry-run", s.handleDryRun)
	mux.HandleFunc("POST /api/policy/publish", s.handlePublish)
	mux.HandleFunc("POST /api/policy/rollback", s.handleRollback)
	mux.HandleFunc("GET /api/secrets", s.handleSecretsList)
	mux.HandleFunc("POST /api/secrets/{name}", s.handleSecretSet)
	mux.HandleFunc("DELETE /api/secrets/{name}", s.handleSecretDelete)
	mux.HandleFunc("GET /api/targets/{id}/credential", s.handleTargetCredential)
	mux.HandleFunc("POST /api/targets/{id}/set-secret", s.handleTargetSetSecret)
	mux.HandleFunc("POST /api/targets/{id}/clear-cooldown", s.handleClearCooldown)
	mux.HandleFunc("POST /api/targets/{id}/set-quota", s.handleSetQuota)
	mux.HandleFunc("GET /api/channels", s.handleChannelsList)
	mux.HandleFunc("POST /api/channels", s.handleChannelCreate)
	mux.HandleFunc("GET /api/channels/{id}", s.handleChannelDetail)
	mux.HandleFunc("PATCH /api/channels/{id}", s.handleChannelPatch)
	mux.HandleFunc("DELETE /api/channels/{id}", s.handleChannelDelete)
	mux.HandleFunc("POST /api/channels/{id}/test", s.handleChannelTest)
	mux.HandleFunc("POST /api/channels/{id}/oauth/login", s.handleChannelOAuthLogin)
	mux.HandleFunc("POST /api/channels/{id}/oauth/callback", s.handleChannelOAuthCallback)
	mux.HandleFunc("GET /api/oauth/accounts", s.handleOAuthAccounts)
	mux.HandleFunc("GET /api/oauth/accounts/{account}/login", s.handleOAuthLoginStatus)
	mux.HandleFunc("DELETE /api/oauth/accounts/{account}/login", s.handleOAuthLoginCancel)
	mux.HandleFunc("DELETE /api/oauth/accounts/{account}", s.handleOAuthAccountDelete)
	mux.Handle("/", s.Routes())
	return mux
}
