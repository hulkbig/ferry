package management

import (
	"context"
	"encoding/json"
	"ferry/internal/config"
	"ferry/internal/domain"
	"ferry/internal/oauth"
	"fmt"
	"net/http"
	"net/http/httptest"
	"reflect"
	"sync/atomic"
	"testing"
	"time"
)

func TestCodexVersionUpdateAndDiscoveryCreateLogicalModelsByDefault(t *testing.T) {
	f := newCodexPrioritySyncFixture(t)
	editCodexUpdateConfig(t, f, func(c *config.File) { c.CodexAutoUpdate = true })
	before := f.server.currentConfig()
	custom := map[string]domain.LogicalModel{}
	for _, m := range before.LogicalModels {
		if !m.AutoGenerated {
			custom[m.ID] = m
		}
	}
	var count atomic.Int32
	count.Store(12) // Codex is not subject to the aggregator-size cap.
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet {
			t.Error("catalog discovery must not send inference")
		}
		models := []map[string]any{}
		for i := 0; i < int(count.Load()); i++ {
			models = append(models, map[string]any{"slug": fmt.Sprintf("gpt-discovered-%d", i), "visibility": "list", "input_modalities": []string{"text"}})
		}
		json.NewEncoder(w).Encode(map[string]any{"models": models})
	}))
	defer srv.Close()
	previous := oauth.CurrentModelCatalogURL()
	oauth.SetModelCatalogURL(srv.URL)
	t.Cleanup(func() { oauth.SetModelCatalogURL(previous) })
	f.server.deps.CodexReleaseHTTPClient = &http.Client{Transport: modelCatalogRoundTripFunc(func(*http.Request) (*http.Response, error) {
		return modelCatalogResponse(200, `{"tag_name":"rust-v0.161.0"}`), nil
	})}
	f.server.syncCodexClientVersion(context.Background())
	f.server.syncDueProviderModels(context.Background(), time.Now())
	deadline := time.Now().Add(5 * time.Second)
	for logicalModelIndex(f.server.currentConfig(), "gpt-discovered-11") < 0 && time.Now().Before(deadline) {
		time.Sleep(10 * time.Millisecond)
	}
	check := func(n int) {
		t.Helper()
		file := f.server.currentConfig()
		for i := 0; i < n; i++ {
			id := fmt.Sprintf("gpt-discovered-%d", i)
			at := logicalModelIndex(file, id)
			if at < 0 {
				t.Fatalf("missing logical model %s", id)
			}
			m := file.LogicalModels[at]
			if !m.AutoGenerated || m.DefaultRoute.Steps[0].UpstreamModel != id {
				t.Fatalf("wrong default route: %+v", m)
			}
		}
		for id, m := range custom {
			at := logicalModelIndex(file, id)
			if at < 0 || !reflect.DeepEqual(file.LogicalModels[at], m) {
				t.Fatalf("custom model %s changed", id)
			}
		}
	}
	check(12)
	// A later explicit sync discovers another model and creates its route too.
	// Wait for the scheduled run's state receipt before invoking manual sync.
	for time.Now().Before(deadline) {
		states, _ := f.control.ProviderModelSyncStates()
		if states["provider-a"].Status == "succeeded" {
			break
		}
		time.Sleep(10 * time.Millisecond)
	}
	count.Store(13)
	rec, _ := f.do(http.MethodPost, "/api/providers/provider-a/models/sync", nil)
	requireStatus(t, rec, http.StatusOK)
	check(13)
}
