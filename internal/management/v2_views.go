func (s *Server) v2RecentProviderRecovery(providerID string, from, to time.Time) []v2RecoveryEventView {
	rows, _, err := s.deps.Ledger.QueryRequests(domain.LogFilter{
		From: from, To: to, Outcome: domain.OutcomeRecoveredSuccess, Limit: 100,
	})
	if err != nil {
		return []v2RecoveryEventView{}
	}
	events := []v2RecoveryEventView{}
	for i := range rows {
		attempts, queryErr := s.deps.Ledger.QueryAttempts(rows[i].ID)
		if queryErr != nil {
			continue
		}
		for index := 1; index < len(attempts); index++ {
			fromAttempt, toAttempt := attempts[index-1], attempts[index]
			if fromAttempt.ProviderID != providerID && toAttempt.ProviderID != providerID {
				continue
			}
			action := "Provider Retry"
			if fromAttempt.ProviderID != toAttempt.ProviderID {
				action = "Provider Fallback"
			}
			events = append(events, v2RecoveryEventView{
				RequestID: rows[i].ID, At: toAttempt.Ts,
				From:   fromAttempt.ProviderID,
				To:     toAttempt.ProviderID,
				Action: action, Result: string(toAttempt.Status), OverheadMS: rows[i].RecoveryAddedLatencyMS,
			})
			if len(events) == 20 {
				return events
			}
		}
	}
	return events
}

func (s *Server) v2ProviderViews(traffic []ledger.TrafficSummary) []v2ProviderView {
	snap := s.deps.Scheduler.Snapshot()
	if snap == nil {
		return []v2ProviderView{}
	}
	trafficByID := map[string]*ledger.TrafficSummary{}
	for i := range traffic {
		trafficByID[traffic[i].ID] = &traffic[i]
	}
	now := time.Now()
	states := s.deps.Manager.ConnectionStates(now)
	connectionAffinity := s.deps.Scheduler.AffinityStatsByConnection(now)
	targetStates := s.deps.Manager.States(now)
	affinity := s.deps.Scheduler.AffinityStatsByProvider(now)
	active := s.deps.Scheduler.ActiveTraffic()
	liveConfig := s.currentConfig()
	syncStates := map[string]controlstore.ProviderModelSyncState{}
	if s.deps.Control != nil {
		if persisted, err := s.deps.Control.ProviderModelSyncStates(); err == nil {
			syncStates = persisted
		}
	}
	ids := make([]string, 0, len(snap.Providers))
	for id := range snap.Providers {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	out := make([]v2ProviderView, 0, len(ids))
	for _, id := range ids {
		provider := snap.Providers[id]
		if provider == nil {
			continue
		}
		view := v2ProviderView{
			ID: provider.ID, Name: provider.Name, Type: provider.Type,
			BaseURL: provider.BaseURL, Enabled: provider.Enabled,
			ModelSyncInterval: provider.ModelSyncInterval.Effective(), ModelSyncCatalog: cloneProviderModelSyncCatalog(provider.ModelSyncCatalog), ProtocolConversion: provider.ProtocolConversion,
			ScheduledMessage: cloneProviderScheduledMessage(provider.ScheduledMessage),
			Concurrency:      cloneConcurrencyPolicy(provider.Concurrency), Traffic: trafficByID[id],
			ActiveTraffic: activeTrafficPhases(active, id), Affinity: affinity[id],
			Quota: map[string]int{"available": 0, "exhausted": 0, "unknown": 0},
		}
		configProvider := findProvider(liveConfig, provider.ID)
		if configProvider == nil {
			configProvider = provider
		}
		stored, hasStored := syncStates[provider.ID]
		if hasStored {
			view.ModelSync = s.modelSyncState(configProvider, liveConfig, &stored)
		} else {
			view.ModelSync = s.modelSyncState(configProvider, liveConfig, nil)
		}
		for _, ref := range provider.Connections {
			if connection := snap.Connections[ref.ID]; connection != nil {
				state := states[connection.ID]
				connectionView := v2ConnectionDTO(snap, connection, state, connectionAffinity[connection.ID])
				if s.deps.OAuth != nil {
					if account, ok := domain.OAuthAccountFromRef(connection.Credential.SecretRef); ok {
						if authorizeURL, started, pending := s.deps.OAuth.PendingLogin(account); pending {
							connectionView.OAuthPending = true
							connectionView.OAuthURL = authorizeURL
							connectionView.OAuthStarted = &started
						}
					}
				}
				view.Connections = append(view.Connections, connectionView)
				view.Quota[string(connectionQuotaAvailability(state, now))]++
			}
		}
		for _, catalog := range snap.ProviderModels {
			if catalog != nil && catalog.ProviderID == id {
				copy := *catalog
				copy.SupportedConnections = append([]string(nil), catalog.SupportedConnections...)
				copy.EligibleConnections = []string{}
				for _, connectionID := range copy.SupportedConnections {
					if s.v2ConnectionEligible(id, connectionID, catalog.UpstreamModel, states, targetStates, now) {
						copy.EligibleConnections = append(copy.EligibleConnections, connectionID)
					}
				}
				view.ModelCatalog = append(view.ModelCatalog, copy)
			}
		}
		sort.Slice(view.ModelCatalog, func(i, j int) bool { return view.ModelCatalog[i].UpstreamModel < view.ModelCatalog[j].UpstreamModel })
		for modelID, model := range snap.LogicalModels {
			if model != nil && modelUsesProvider(model, id) {
				view.UsedByModels = append(view.UsedByModels, modelID)
			}
		}
		sort.Strings(view.UsedByModels)
		for _, catalog := range view.ModelCatalog {
			used := []string{}
			for modelID, model := range snap.LogicalModels {
				if model != nil && modelUsesProviderModel(model, id, catalog.UpstreamModel) {
					used = append(used, modelID)
				}
			}
			if len(used) > 0 {
				sort.Strings(used)
				view.SupplyInUse = append(view.SupplyInUse, v2SupplyInUseView{
					UpstreamModel: catalog.UpstreamModel, LogicalModels: used,
					EligibleConnections: len(catalog.EligibleConnections),
				})
			}
		}
		if view.Connections == nil {
			view.Connections = []v2ConnectionView{}
		}
		if view.ModelCatalog == nil {
			view.ModelCatalog = []domain.ProviderModel{}
		}
		if view.SupplyInUse == nil {
			view.SupplyInUse = []v2SupplyInUseView{}
		}
		if view.UsedByModels == nil {
			view.UsedByModels = []string{}
		}
		if view.Traffic == nil {
			view.Traffic = &ledger.TrafficSummary{ID: id}
		}
		view.Recovery = v2ProviderRecoveryView{
			DirectTraffic: view.Traffic.DirectTraffic, RecoveryTraffic: view.Traffic.RecoveryTraffic,
			Failed: view.Traffic.Failed,
		}
		view.State, view.AvailableConnections = v2ProviderState(provider.Enabled, view.Connections, now)
		out = append(out, view)
	}
	return out
}

func v2ConnectionDTO(snapshot *domain.CompiledSnapshot, connection *domain.Connection, state domain.ConnectionState, affinity sched.AffinityStats) v2ConnectionView {
	view := v2ConnectionView{
		ID: connection.ID, ProviderID: connection.ProviderID, Identity: connection.Identity,
		BaseURL: connection.BaseURL, FullURL: connection.FullURL, Enabled: connection.Enabled, CredentialRef: connection.Credential.SecretRef,
		Concurrency: cloneConcurrencyPolicy(connection.Concurrency), Runtime: state, Affinity: affinity,
	}
	for _, model := range connection.Models {
		upstream := model.Capabilities
		targetID := model.ExecutionTargetID
		if targetID == "" {
			targetID = connection.RuntimeTargetID(model.UpstreamModel)
		}
		if snapshot != nil {
			if target := snapshot.Targets[targetID]; target != nil {
				upstream = target.Capabilities
			}
		}
		view.Models = append(view.Models, v2ConnectionModelView{
			UpstreamModel: model.UpstreamModel, Protocols: append([]domain.Protocol(nil), model.Protocols...),
			UpstreamCapabilities: upstream, Capabilities: domain.EffectiveCapabilities(upstream), PlanID: model.PlanID,
		})
	}
	if view.Models == nil {
		view.Models = []v2ConnectionModelView{}
	}
	return view
}

func v2ProviderState(enabled bool, connections []v2ConnectionView, now time.Time) (string, int) {
	if !enabled || len(connections) == 0 {
		return "unavailable", 0
	}
	available, enabledConnections, cooling := 0, 0, 0
	for _, connection := range connections {
		if !connection.Enabled {
			continue
		}
		enabledConnections++
		switch v2ConnectionRole(connection, now) {
		case "serving", "standby":
			available++
		case "cooling":
			cooling++
		}
	}
	switch {
	case enabledConnections == 0:
		return "unavailable", 0
	case available == 0 && cooling > 0:
		return "exhausted", 0
	case available == 0:
		return "unavailable", 0
	case available < enabledConnections:
		return "recovering", available
	default:
		return "healthy", available
	}
}

func v2ConnectionRole(connection v2ConnectionView, now time.Time) string {
	state := connection.Runtime
	if !connection.Enabled || state.Auth == domain.ConnectionAuthError || state.Reachability == domain.ConnectionOffline {
		return "unavailable"
	}
	if state.CoolingUntil.After(now) || connectionQuotaAvailability(state, now) == domain.QuotaExhausted {
		return "cooling"
	}
	if state.InFlight > 0 {
		return "serving"
	}
	return "standby"
}

func modelUsesProvider(model *domain.LogicalModel, providerID string) bool {
	for _, step := range model.DefaultRoute.Steps {
		if step.ProviderID == providerID {
			return true
		}
	}
	for _, override := range model.Overrides {
		for _, step := range override.Prefer {
			if step.ProviderID == providerID {
				return true
			}
		}
		for _, step := range override.Avoid {
			if step.ProviderID == providerID {
				return true
			}
		}
		if override.Route != nil {
			for _, step := range override.Route.Steps {
				if step.ProviderID == providerID {
					return true
				}
			}
		}
	}
	return false
}

func modelUsesProviderModel(model *domain.LogicalModel, providerID, upstreamModel string) bool {
	uses := func(step domain.RouteStep) bool {
		return step.ProviderID == providerID && step.UpstreamModel == upstreamModel
	}
	for _, step := range model.DefaultRoute.Steps {
		if uses(step) {
			return true
		}
	}
	for _, override := range model.Overrides {
		for _, step := range append(append([]domain.RouteStep{}, override.Prefer...), override.Avoid...) {
			if uses(step) {
				return true
			}
		}
		if override.Route != nil {
			for _, step := range override.Route.Steps {
				if uses(step) {
					return true
				}
			}
		}
	}
	return false
}

func connectionQuotaAvailability(state domain.ConnectionState, now time.Time) domain.QuotaAvailability {
	availability := domain.QuotaUnknown
	for _, window := range state.QuotaWindows {
		if window.Availability == domain.QuotaExhausted && (window.ResetAt.IsZero() || window.ResetAt.After(now)) {
			return domain.QuotaExhausted
		}
		if window.Availability == domain.QuotaAvailable {
			availability = domain.QuotaAvailable
		}
	}
	return availability
}

func activeTrafficPhases(records []sched.ActiveTrafficRecord, providerID string) map[string]int {
	out := map[string]int{"total": 0, "waiting": 0, "active": 0, "recovering": 0, "streaming": 0}
	for _, record := range records {
		if providerID != "" && record.ProviderID != providerID {
			continue
		}
		out["total"]++
		out[string(record.Phase)]++
	}
	return out
}

func aggregateActiveTraffic(records []sched.ActiveTrafficRecord) map[string]any {
	byModel := map[string]map[string]int{}
	byProvider := map[string]map[string]int{}
	for _, record := range records {
		if byModel[record.LogicalModelID] == nil {
			byModel[record.LogicalModelID] = map[string]int{}
		}
		byModel[record.LogicalModelID][string(record.Phase)]++
		if record.ProviderID != "" {
			if byProvider[record.ProviderID] == nil {
				byProvider[record.ProviderID] = map[string]int{}
			}
			byProvider[record.ProviderID][string(record.Phase)]++
		}
	}
	return map[string]any{"requests": len(records), "by_model": byModel, "by_provider": byProvider}
}

func (s *Server) handleV2Requests(w http.ResponseWriter, r *http.Request) {
	from, to, err := v2RequestWindow(r)
	if err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	filter := domain.LogFilter{From: from, To: to, Limit: 100}
	if value, err := strconv.Atoi(r.URL.Query().Get("limit")); err == nil && value > 0 {
		filter.Limit = min(value, 1000)
	}
	if value, err := strconv.Atoi(r.URL.Query().Get("offset")); err == nil && value >= 0 {
		filter.Offset = value
	}
	if raw := strings.TrimSpace(r.URL.Query().Get("from")); raw != "" {
		value, parseErr := time.Parse(time.RFC3339, raw)
		if parseErr != nil {
			writeMgmtErr(w, http.StatusBadRequest, "from must be RFC3339")
			return
		}
		filter.From = value
	}
	if raw := strings.TrimSpace(r.URL.Query().Get("to")); raw != "" {
		value, parseErr := time.Parse(time.RFC3339, raw)
		if parseErr != nil {
			writeMgmtErr(w, http.StatusBadRequest, "to must be RFC3339")
			return
		}
		filter.To = value
	}
	filter.RequestID = r.URL.Query().Get("request_id")
	filter.Search = r.URL.Query().Get("q")
	filter.ConsumerKey = r.URL.Query().Get("api_key")
	filter.ProviderID = r.URL.Query().Get("provider")
	filter.ParticipatingProvider = r.URL.Query().Get("participating_provider")
	filter.LogicalModel = r.URL.Query().Get("logical_model")
	filter.AttemptStatus = r.URL.Query().Get("attempt_status")
	filter.AttemptFailureType = r.URL.Query().Get("attempt_failure_type")
	filter.ReportError = r.URL.Query().Get("report_error")
	filter.ConnectionID = r.URL.Query().Get("connection")
	filter.ConversationID = r.URL.Query().Get("conversation_id")
	filter.Outcome = domain.RequestOutcome(strings.ToUpper(r.URL.Query().Get("outcome")))
	filter.Status = domain.RequestStatus(strings.ToLower(r.URL.Query().Get("status")))
	filter.Model = r.URL.Query().Get("model")
	filter.FailureType = domain.FailureType(r.URL.Query().Get("failure_type"))
	if value, parseErr := strconv.ParseInt(r.URL.Query().Get("runtime_revision"), 10, 64); parseErr == nil && value > 0 {
		filter.RuntimeRevision = value
	}
	rows, total, err := s.deps.Ledger.QueryRequests(filter)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	items := make([]map[string]any, 0, len(rows))
	for i := range rows {
		conversationID := ""
		if trace, traceErr := s.deps.Ledger.QueryTrace(rows[i].ID); traceErr == nil && trace != nil {
			conversationID = trace.ConversationID
		}
		item := v2RequestSummary(&rows[i], conversationID)
		s.addReferencePricing(item, &rows[i])
		items = append(items, item)
	}
	writeMgmtJSON(w, http.StatusOK, map[string]any{"total": total, "requests": items})
}

