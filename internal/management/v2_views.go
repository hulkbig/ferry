func (s *Server) v2ModelViews(traffic []ledger.RouteTrafficSummary) []v2ModelView {
	snap := s.deps.Scheduler.Snapshot()
	if snap == nil {
		return []v2ModelView{}
	}
	now := time.Now()
	connectionStates := s.deps.Manager.ConnectionStates(now)
	targetStates := s.deps.Manager.States(now)
	trafficCounts := map[string]int64{}
	modelTotals := map[string]int64{}
	for _, item := range traffic {
		key := item.LogicalModelID + "\x00" + item.ProviderID + "\x00" + item.UpstreamModel
		trafficCounts[key] += item.Requests
		modelTotals[item.LogicalModelID] += item.Requests
	}
	ids := make([]string, 0, len(snap.LogicalModels))
	for id := range snap.LogicalModels {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	out := make([]v2ModelView, 0, len(ids))
	for _, id := range ids {
		model := snap.LogicalModels[id]
		if model == nil {
			continue
		}
		view := v2ModelView{
			ID: model.ID, DisplayName: model.DisplayName, Description: model.Description, AutoGenerated: model.AutoGenerated,
			Enabled: model.Enabled, ExactOnly: model.ExactOnly, ExistingConversationStrategy: model.ExistingConversationStrategy,
			FirstOutputTimeoutSeconds: model.FirstOutputTimeoutSeconds,
			Overrides:                 append([]domain.OverrideSpec(nil), model.Overrides...),
		}
		for _, step := range model.DefaultRoute.Steps {
			stepView := v2RouteStepView{
				ProviderID: step.ProviderID, UpstreamModel: step.UpstreamModel,
				RecoverOn: cloneV2RecoveryFailures(step.RecoverOn), RuntimeState: "unavailable",
			}
			catalog := snap.ProviderModels[domain.ProviderModelKey(step.ProviderID, step.UpstreamModel)]
			if catalog != nil {
				stepView.TotalConnections = len(catalog.SupportedConnections)
				for _, connectionID := range catalog.SupportedConnections {
					if s.v2ConnectionEligible(step.ProviderID, connectionID, step.UpstreamModel,
						connectionStates, targetStates, now) {
						stepView.EligibleConnections++
					}
				}
			}
			if stepView.EligibleConnections > 0 {
				stepView.RuntimeState = "available"
			}
			if total := modelTotals[id]; total > 0 {
				key := id + "\x00" + step.ProviderID + "\x00" + step.UpstreamModel
				stepView.LiveTrafficShare = float64(trafficCounts[key]) / float64(total)
			}
			view.DefaultRoute = append(view.DefaultRoute, stepView)
		}
		view.State, view.RuntimeSentence = v2ModelState(model.Enabled, view.DefaultRoute)
		out = append(out, view)
	}
	return out
}

func v2ModelState(enabled bool, steps []v2RouteStepView) (string, string) {
	availableSteps := 0
	for _, step := range steps {
		if step.EligibleConnections > 0 {
			availableSteps++
		}
	}
	switch {
	case !enabled || availableSteps == 0:
		return "unavailable", "No configured route step is currently eligible."
	case len(steps) > 0 && steps[0].EligibleConnections == 0:
		return "protected", "The primary route is unavailable; a later route step can continue serving traffic."
	case availableSteps == len(steps):
		return "healthy", "The primary route and configured protection capacity are available."
	default:
		return "degraded", "The primary route is serving, but part of the configured protection capacity is unavailable."
	}
}

func enrichV2Models(models []v2ModelView, traffic []ledger.TrafficSummary) {
	byID := map[string]ledger.TrafficSummary{}
	for _, item := range traffic {
		byID[item.ID] = item
	}
	for i := range models {
		item := byID[models[i].ID]
		item.ID = models[i].ID
		models[i].Traffic = &item
	}
}

func (s *Server) v2ConnectionEligible(providerID, connectionID, upstreamModel string,
	connectionStates map[string]domain.ConnectionState,
	targetStates map[domain.ResourceTargetID]domain.TargetState, now time.Time) bool {
	snap := s.deps.Scheduler.Snapshot()
	provider := snap.Providers[providerID]
	connection := snap.Connections[connectionID]
	if provider == nil || connection == nil || !provider.Enabled || !connection.Enabled {
		return false
	}
	targetID, found := v2RuntimeTargetID(snap, providerID, connectionID, upstreamModel)
	if !found {
		return false
	}
	if !s.deps.Scheduler.HasCaller(targetID) {
		return false
	}
	state := connectionStates[connectionID]
	if state.Auth == domain.ConnectionAuthError || state.Reachability == domain.ConnectionOffline || state.CoolingUntil.After(now) {
		return false
	}
	for _, quota := range state.QuotaWindows {
		if quota.Availability == domain.QuotaExhausted && (quota.ResetAt.IsZero() || quota.ResetAt.After(now)) {
			return false
		}
	}
	target := targetStates[targetID]
	return target.Breaker != domain.BreakerOpen && !target.CooldownUntil.After(now) && !target.QuotaExhausted()
}

func v2RuntimeTargetID(snap *domain.CompiledSnapshot, providerID, connectionID, upstreamModel string) (domain.ResourceTargetID, bool) {
	if snap == nil {
		return "", false
	}
	for _, id := range snap.TargetOrder {
		target := snap.Targets[id]
		if target != nil && target.ProviderID == providerID && target.ConnectionID == connectionID && target.Model == upstreamModel {
			return id, true
		}
	}
	// Compatibility for snapshots produced before TargetOrder was persisted.
	for id, target := range snap.Targets {
		if target != nil && target.ProviderID == providerID && target.ConnectionID == connectionID && target.Model == upstreamModel {
			return id, true
		}
	}
	return "", false
}

