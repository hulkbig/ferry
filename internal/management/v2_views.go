func v2WindowDuration(r *http.Request) (time.Duration, error) {
	duration := 24 * time.Hour
	if raw := strings.TrimSpace(r.URL.Query().Get("window")); raw != "" {
		parsed, err := time.ParseDuration(raw)
		if err != nil || parsed < time.Millisecond || parsed > 90*24*time.Hour {
			return 0, &v2InputError{"window must be a duration between 1ms and 2160h"}
		}
		duration = parsed
	}
	return duration, nil
}

func v2RequestWindow(r *http.Request) (time.Time, time.Time, error) {
	duration, err := v2WindowDuration(r)
	if err != nil {
		return time.Time{}, time.Time{}, err
	}
	to := time.Now()
	return to.Add(-duration), to, nil
}

func v2Window(r *http.Request) (time.Time, time.Time, error) {
	query := r.URL.Query()
	hasFrom, hasTo := query.Has("from"), query.Has("to")
	hasWindow := strings.TrimSpace(query.Get("window")) != ""
	if hasFrom && !hasTo {
		return time.Time{}, time.Time{}, &v2InputError{"from requires to for aggregate windows"}
	}
	if hasFrom && hasTo && hasWindow {
		return time.Time{}, time.Time{}, &v2InputError{"window cannot be combined with both from and to"}
	}

	now := time.Now()
	if hasFrom {
		from, err := time.Parse(time.RFC3339, query.Get("from"))
		if err != nil {
			return time.Time{}, time.Time{}, &v2InputError{"from must be RFC3339"}
		}
		to, err := time.Parse(time.RFC3339, query.Get("to"))
		if err != nil {
			return time.Time{}, time.Time{}, &v2InputError{"to must be RFC3339"}
		}
		return validateV2Window(from, to, now)
	}

	duration, err := v2WindowDuration(r)
	if err != nil {
		return time.Time{}, time.Time{}, err
	}
	to := now
	if hasTo {
		to, err = time.Parse(time.RFC3339, query.Get("to"))
		if err != nil {
			return time.Time{}, time.Time{}, &v2InputError{"to must be RFC3339"}
		}
	}
	return validateV2Window(to.Add(-duration), to, now)
}

func validateV2Window(from, to, now time.Time) (time.Time, time.Time, error) {
	if to.After(now) {
		return time.Time{}, time.Time{}, &v2InputError{"to must not be in the future"}
	}
	duration := to.Sub(from)
	if duration < time.Millisecond || duration > 90*24*time.Hour {
		return time.Time{}, time.Time{}, &v2InputError{"aggregate window must span between 1ms and 2160h"}
	}
	return from, to, nil
}

type v2InputError struct{ message string }

func (e *v2InputError) Error() string { return e.message }

func (s *Server) handleV2Overview(w http.ResponseWriter, r *http.Request) {
	from, to, err := v2Window(r)
	if err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	usage, err := s.deps.Ledger.Summarize(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	cacheHit, err := s.deps.Ledger.CacheHitOverview(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	trend, err := s.deps.Ledger.UsageTrend(from, to, 24)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	trafficTrend, err := s.deps.Ledger.TrafficTrend(from, to, 24)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	outcomes, err := s.deps.Ledger.OutcomeSummary(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	byModel, err := s.deps.Ledger.TrafficByLogicalModel(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	byProvider, err := s.deps.Ledger.TrafficByProvider(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	routeTraffic, err := s.deps.Ledger.TrafficByRoute(from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	models := s.v2ModelViews(routeTraffic)
	enrichV2Models(models, byModel)
	protection := map[string]int{"healthy": 0, "protected": 0, "degraded": 0, "unavailable": 0}
	needsAttention := []string{}
	managedSet := map[string]bool{}
	enabledModels := map[string]bool{}
	for _, model := range models {
		if !model.Enabled {
			continue
		}
		enabledModels[model.ID] = true
		protection[model.State]++
		switch model.State {
		case "degraded", "unavailable":
			needsAttention = append(needsAttention, model.ID)
		case "protected":
			managedSet[model.ID] = true
		}
	}
	for _, traffic := range byModel {
		if enabledModels[traffic.ID] && traffic.RecoveryTraffic > 0 {
			managedSet[traffic.ID] = true
		}
	}
	managed := make([]string, 0, len(managedSet))
	for id := range managedSet {
		managed = append(managed, id)
	}
	sort.Strings(managed)
	clientStatus := "no_traffic"
	if usage.Requests > 0 {
		clientStatus = "healthy"
		if outcomes.Failed > 0 {
			clientStatus = "degraded"
		}
	}
	configurationStatus := "healthy"
	if len(needsAttention) > 0 {
		configurationStatus = "needs_attention"
	}
	// Overall is the Ferry runtime/API availability signal. Client outcomes
	// and model configuration remain independent diagnostics and must not turn
	// a healthy service into a global degraded state because a few requests or
	// individual routes failed within the selected historical window.
	overallStatus := "available"
	quota := map[string]int{"available": 0, "exhausted": 0, "unknown": 0}
	if s.deps.Manager != nil {
		for _, state := range s.deps.Manager.ConnectionStates(to) {
			availability := domain.QuotaUnknown
			for _, window := range state.QuotaWindows {
				if window.Availability == domain.QuotaExhausted {
					availability = domain.QuotaExhausted
					break
				}
				if window.Availability == domain.QuotaAvailable {
					availability = domain.QuotaAvailable
				}
			}
			quota[string(availability)]++
		}
	}
	successRate := 1.0
	if usage.Requests > 0 {
		successRate = float64(usage.Succeeded) / float64(usage.Requests)
	}
	activeConversations := 0
	for _, stats := range s.deps.Scheduler.AffinityStatsByProvider(to) {
		activeConversations += stats.Conversation
	}
	minutes := to.Sub(from).Minutes()
	requestRate, tokenRate := float64(0), float64(0)
	if minutes > 0 {
		requestRate = float64(usage.Requests) / minutes
		tokenRate = float64(usage.InputTokens+usage.OutputTokens) / minutes
	}
	writeMgmtJSON(w, http.StatusOK, map[string]any{
		"from": from, "to": to,
		"status": map[string]any{
			"overall": overallStatus, "client_traffic": clientStatus,
			"runtime_api": "available", "configuration": configurationStatus,
		},
		"client_experience": map[string]any{"success_rate": successRate, "requests": usage.Requests},
		"client_outcomes":   outcomes,
		"rates": map[string]any{
			"requests_per_minute": requestRate, "tokens_per_minute": tokenRate,
		},
		"active_conversations": activeConversations,
		"live_traffic": map[string]any{
			"active":          aggregateActiveTraffic(s.deps.Scheduler.ActiveTraffic()),
			"window_by_model": byModel, "window_by_provider": byProvider,
		},
		"protection":            protection,
		"model_protection":      models,
		"needs_attention":       needsAttention,
		"managed_automatically": managed,
		"quota_summary":         quota,
		"usage_summary":         usage,
		"cache_hit_summary":     cacheHit,
		"trend":                 trend,
		"traffic_trend":         trafficTrend,
	})
}

