func (s *Server) handleV2SettingsPatch(w http.ResponseWriter, r *http.Request) {
	if s.deps.Ledger == nil {
		writeMgmtErr(w, http.StatusServiceUnavailable, "ledger is not configured")
		return
	}
	var patch struct {
		UsageProtection          *oauth.UsageProtection     `json:"codex_usage_protection"`
		AutomaticUsageReset      *automaticUsageResetPolicy `json:"codex_usage_reset_auto"`
		Concurrency              *domain.ConcurrencyPolicy  `json:"concurrency"`
		ExpectedRevision         *int64                     `json:"expected_revision"`
		Backup                   *backupPolicyPatch         `json:"backup"`
		DebugRequestResponse     *bool                      `json:"debug_request_response"`
		ScheduledModelSyncEnable *bool                      `json:"scheduled_model_sync_enabled"`
		AutoLogicalModelLimit    *int                       `json:"auto_logical_model_limit"`
		PricingSync              *pricingsync.Settings      `json:"pricing_sync"`
	}
	if err := decodeMgmtBody(r, &patch); err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	if patch.UsageProtection != nil {
		if err := patch.UsageProtection.Validate(); err != nil {
			writeMgmtErr(w, http.StatusBadRequest, err.Error())
			return
		}
	}
	if patch.AutomaticUsageReset != nil {
		if err := patch.AutomaticUsageReset.validate(); err != nil {
			writeMgmtErr(w, http.StatusBadRequest, err.Error())
			return
		}
	}
	if patch.Backup != nil {
		if s.deps.Control == nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, "control store is not configured")
			return
		}
		if err := s.prepareBackupPatch(patch.Backup); err != nil {
			writeMgmtErr(w, http.StatusBadRequest, err.Error())
			return
		}
	}
	if patch.PricingSync != nil {
		if err := pricingsync.ValidateSettings(*patch.PricingSync); err != nil {
			writeMgmtErr(w, http.StatusBadRequest, err.Error())
			return
		}
	}
	if patch.AutoLogicalModelLimit != nil && (*patch.AutoLogicalModelLimit < 0 || *patch.AutoLogicalModelLimit > 10000) {
		writeMgmtErr(w, http.StatusBadRequest, "auto_logical_model_limit must be between 0 and 10000")
		return
	}
	if err := patch.Concurrency.Validate(); err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	if patch.Concurrency != nil {
		s.configMu.Lock()
		revision, err := s.controlVersionLocked()
		if err != nil || patch.ExpectedRevision == nil || *patch.ExpectedRevision != revision {
			s.configMu.Unlock()
			writeMgmtErr(w, http.StatusConflict, "reload settings before saving concurrency")
			return
		}
		next, err := cloneConfig(s.deps.Config)
		if err == nil {
			next.Concurrency = cloneConcurrencyPolicy(patch.Concurrency)
			err = s.publishConfig(next)
		}
		s.configMu.Unlock()
		if err != nil {
			writeMgmtErr(w, http.StatusUnprocessableEntity, err.Error())
			return
		}
	}
	if patch.UsageProtection == nil && patch.AutomaticUsageReset == nil && patch.DebugRequestResponse == nil && patch.ScheduledModelSyncEnable == nil && patch.AutoLogicalModelLimit == nil && patch.PricingSync == nil && patch.Backup == nil && patch.Concurrency == nil {
		writeMgmtErr(w, http.StatusBadRequest, "at least one settings field is required")
		return
	}
	if patch.Backup != nil {
		if err := s.saveBackupPatch(patch.Backup); err != nil {
			writeMgmtErr(w, http.StatusInternalServerError, err.Error())
			return
		}
	}
	if patch.PricingSync != nil {
		if err := s.pricing.Configure(*patch.PricingSync); err != nil {
			writeMgmtErr(w, http.StatusConflict, err.Error())
			return
		}
	}
	if patch.DebugRequestResponse != nil {
		if err := s.deps.Ledger.SetDebugCapture(*patch.DebugRequestResponse); err != nil {
			writeMgmtErr(w, http.StatusInternalServerError, err.Error())
			return
		}
	}
	if patch.AutomaticUsageReset != nil {
		if err := s.saveAutomaticUsageResetPolicy(*patch.AutomaticUsageReset); err != nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, err.Error())
			return
		}
	}
	if patch.UsageProtection != nil {
		if err := s.saveUsageProtectionPolicy(*patch.UsageProtection); err != nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, err.Error())
			return
		}
	}
	if patch.ScheduledModelSyncEnable != nil {
		if err := s.setScheduledModelSyncEnabled(*patch.ScheduledModelSyncEnable); err != nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, err.Error())
			return
		}
	}
	if patch.AutoLogicalModelLimit != nil {
		s.configMu.Lock()
		next, err := cloneConfig(s.deps.Config)
		if err == nil {
			next.AutoLogicalModelLimit = patch.AutoLogicalModelLimit
			err = s.publishConfig(next)
		}
		s.configMu.Unlock()
		if err != nil {
			writeMgmtErr(w, http.StatusUnprocessableEntity, err.Error())
			return
		}
	}
	s.handleV2SettingsGet(w, r)
}

func (s *Server) handleV2ModelSimulate(w http.ResponseWriter, r *http.Request) {
	var body struct {
		CallerID string              `json:"caller_id"`
		Protocol domain.Protocol     `json:"protocol"`
		Stream   bool                `json:"stream"`
		Required domain.Requirements `json:"required_capabilities"`
		At       string              `json:"at"`
	}
	if err := decodeMgmtBody(r, &body); err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	if body.Protocol == "" {
		body.Protocol = domain.ProtocolOpenAIChat
	}
	if err := validateV2SimulationInput(body.Protocol, body.Required); err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	effectiveAt := time.Now()
	if strings.TrimSpace(body.At) != "" {
		parsed, err := time.Parse(time.RFC3339, body.At)
		if err != nil {
			writeMgmtErr(w, http.StatusBadRequest, "at must be RFC3339")
			return
		}
		effectiveAt = parsed
	}
	simulatedAt := &effectiveAt
	modelID := r.PathValue("id")
	snapshot := s.deps.Scheduler.Snapshot()
	if snapshot == nil {
		writeMgmtErr(w, http.StatusServiceUnavailable, "scheduler snapshot is not initialized")
		return
	}
	previewingDisabledModel := false
	if configured := snapshot.LogicalModels[modelID]; configured == nil {
		writeMgmtErr(w, http.StatusNotFound, "logical model not found")
		return
	} else if !configured.Enabled {
		// Simulation is a configuration preview, not a live request. A disabled
		// model with a valid route must therefore remain simulatable without first
		// exposing it to client traffic. Compile an unpublished snapshot with only
		// this model temporarily enabled and evaluate it through the same planner.
		candidate, err := cloneConfig(s.currentConfig())
		if err != nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, err.Error())
			return
		}
		index := logicalModelIndex(candidate, modelID)
		if index < 0 {
			writeMgmtErr(w, http.StatusNotFound, "logical model not found")
			return
		}
		candidate.LogicalModels[index].Enabled = true
		if err := candidate.Validate(); err != nil {
			writeMgmtErr(w, http.StatusUnprocessableEntity,
				"route cannot be simulated until its configuration is valid: "+err.Error())
			return
		}
		if s.deps.Compiler == nil {
			writeMgmtErr(w, http.StatusServiceUnavailable, "configuration compiler is not available")
			return
		}
		snapshot, err = s.deps.Compiler.Compile(candidate)
		if err != nil {
			writeMgmtErr(w, http.StatusUnprocessableEntity,
				"route cannot be simulated until it compiles: "+err.Error())
			return
		}
		previewingDisabledModel = true
	}
	callerID := body.CallerID
	if callerID == "" && s.deps.APIKeys != nil {
		identities, _, _ := s.deps.APIKeys.APIKeys()
		for _, identity := range identities {
			if identity.Enabled {
				callerID = identity.ID
				break
			}
		}
	}
	contract := &domain.RequestContract{
		Model: modelID, Protocol: body.Protocol, Origin: body.Protocol, Stream: body.Stream,
		Messages: []domain.Message{{Role: domain.RoleUser, Blocks: []domain.Block{{Kind: domain.BlockText, Text: "simulation"}}}},
	}
	if body.Required.Tools || body.Required.ParallelTools {
		contract.Tools = []domain.ToolDef{{Name: "simulation", Parameters: json.RawMessage(`{}`)}}
	}
	if body.Required.ParallelTools {
		parallel := true
		contract.ParallelTools = &parallel
	}
	if body.Required.Reasoning {
		contract.Reasoning = &domain.ReasoningSpec{Effort: "medium"}
	}
	if body.Required.StructuredOutput {
		contract.ResponseFormat = &domain.ResponseFormat{Name: "simulation", Schema: []byte(`{"type":"object"}`)}
	}
	simulation, failure := s.deps.Scheduler.DryRunV2Snapshot(snapshot, contract, sched.RequestMeta{
		CallerID: callerID, RequiredCapabilities: &body.Required, SimulatedAt: simulatedAt,
	})
	if simulation == nil && failure != nil {
		writeMgmtErr(w, failureStatus(failure), failure.Message)
		return
	}
	if simulation == nil {
		writeMgmtErr(w, http.StatusServiceUnavailable, "route simulation produced no plan")
		return
	}
	candidates := make([]map[string]any, 0, len(simulation.Plan.Candidates))
	for _, candidate := range simulation.Plan.Candidates {
		item := map[string]any{"eligible": candidate.Eligible, "rank": candidate.Rank, "exclusion_reason": candidate.ExclusionReason}
		item["capability_status"] = candidate.CapabilityStatuses
		if target := snapshot.Targets[candidate.Target]; target != nil {
			item["provider_id"] = target.ProviderID
			item["connection_id"] = target.ConnectionID
			item["upstream_model"] = target.Model
			egress := target.EgressProtocol(body.Protocol)
			item["upstream_capabilities"] = target.UpstreamCapabilitiesFor(egress)
			item["capabilities"] = target.CapabilitiesFor(egress)
		}
		candidates = append(candidates, item)
	}
	expected := map[string]any{}
	if target := snapshot.Targets[simulation.Plan.Primary]; target != nil {
		expected = map[string]any{"provider_id": target.ProviderID, "connection_id": target.ConnectionID, "upstream_model": target.Model}
	}
	response := map[string]any{
		"logical_model_id": simulation.LogicalModelID, "matched_override": simulation.OverrideID,
		"default_route": simulation.DefaultRoute, "effective_route": simulation.EffectiveRoute,
		"connection_candidates": candidates, "expected_selection": expected,
		"previewing_disabled_model": previewingDisabledModel,
	}
	if failure != nil {
		response["planning_failure"] = failure
	}
	response["simulated_at"] = effectiveAt
	writeMgmtJSON(w, http.StatusOK, response)
}

func validateV2SimulationInput(protocol domain.Protocol, required domain.Requirements) error {
	if !domain.ValidProtocol(protocol) {
		return fmt.Errorf("unsupported simulation protocol %q", protocol)
	}
	if required.MinContext < 0 || required.MinOutput < 0 {
		return fmt.Errorf("simulation capability minima must be non-negative")
	}
	return nil
}

func failureStatus(failure *domain.Failure) int {
	if failure == nil {
		return http.StatusInternalServerError
	}
	switch failure.Type {
	case domain.FailAuth:
		return http.StatusUnauthorized
	case domain.FailUnsupportedParam:
		return http.StatusUnprocessableEntity
	default:
		return http.StatusServiceUnavailable
	}
}

func (s *Server) handleV2Organizations(w http.ResponseWriter, _ *http.Request) {
	// Ferry is currently a single-administrator, single-tenant control
	// plane. Expose that capability boundary instead of manufacturing tenant
	// isolation or synthetic members.
	writeMgmtJSON(w, http.StatusOK, map[string]any{
		"organization_scope_supported": false,
		"organizations": []map[string]any{{
			"id": "local", "name": "Local Ferry", "role": "Owner", "members": nil,
		}},
	})
}

func (s *Server) handleV2UsageBilling(w http.ResponseWriter, r *http.Request) {
	from, to, err := v2Window(r)
	if err != nil {
		writeMgmtErr(w, http.StatusBadRequest, err.Error())
		return
	}
	report, err := s.deps.Ledger.QueryBilling(r.Context(), from, to)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	w.Header().Set("Cache-Control", "no-store")
	writeMgmtJSON(w, http.StatusOK, report)
}

func (s *Server) backupSettings() any {
	if s.deps.Control == nil {
		return map[string]any{"error": "control store is not configured"}
	}
	p, err := backuppolicy.Load(s.deps.Control)
	if err != nil {
		return map[string]any{"error": "backup policy could not be loaded"}
	}
	return p
}
