func (s *Server) handleV2RequestDetail(w http.ResponseWriter, r *http.Request) {
	record, err := s.deps.Ledger.QueryRequest(r.PathValue("id"))
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	if record == nil {
		writeMgmtErr(w, http.StatusNotFound, "request not found")
		return
	}
	attempts, err := s.deps.Ledger.QueryAttempts(record.ID)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	trace, err := s.deps.Ledger.QueryTrace(record.ID)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	snap := s.deps.Scheduler.Snapshot()
	attemptViews := make([]map[string]any, 0, len(attempts))
	for _, attempt := range attempts {
		view := map[string]any{
			"sequence": attempt.Seq, "timestamp": attempt.Ts, "protocol": attempt.Protocol,
			"provider_id": attempt.ProviderID, "connection_id": attempt.ConnectionID,
			"upstream_model": attempt.Model, "status": attempt.Status, "failure": attempt.Failure,
			"service_tier": attempt.ServiceTier, "response_model": attempt.ResponseModel, "response_service_tier": attempt.ResponseServiceTier,
			"service_tier_evidence": attempt.ServiceTierEvidence,
			"latency_ms":            attempt.LatencyMS, "ttft_ms": attempt.TTFTMS, "usage": attempt.Usage,
			"estimated_cash_cost": attempt.EstCashCost,
			"allocated_sub_cost":  attempt.AllocatedSubCost, "shadow_cost": attempt.ShadowCost,
			"rate_card_version": attempt.RateCardVersion, "plan_kind": attempt.PlanKind,
			"multiplier": attempt.Multiplier, "quota_units": attempt.QuotaUnits,
		}
		if (attempt.ProviderID == "" || attempt.ConnectionID == "") && snap != nil {
			if target := snap.Targets[attempt.TargetID]; target != nil {
				if attempt.ProviderID == "" {
					view["provider_id"] = target.ProviderID
				}
				if attempt.ConnectionID == "" {
					view["connection_id"] = target.ConnectionID
				}
			}
		}
		attemptViews = append(attemptViews, view)
	}
	events := []domain.ExecutionTraceEvent{}
	if trace != nil {
		events = append(events, trace.Events...)
	}
	response := map[string]any{
		"client_request": v2RequestSummary(record, func() string {
			if trace != nil {
				return trace.ConversationID
			}
			return ""
		}()),
		"attempts":               attemptViews,
		"execution_trace_events": events,
		"client_impact": map[string]any{
			"outcome": record.Outcome, "visible_error": record.Status != domain.ReqSuccess && !record.CommitAt.IsZero(),
			"recovery_added_latency_ms": record.RecoveryAddedLatencyMS,
		},
		"resource_impact": map[string]any{
			"connection_recovery_count": record.ConnectionRebindCount,
			"recovery_fallback_count":   record.RecoveryFallbackCount,
			"route_advance_count":       record.RouteAdvanceCount,
			"logical_usage":             record.Usage, "upstream_usage": record.UpstreamUsage,
			"serving_cost": record.ServingCost, "recovery_overhead_cost": record.RecoveryOverheadCost,
			"total_cost": record.ServingCost + record.RecoveryOverheadCost,
		},
		"continuity":       map[string]any{"mode": record.ContinuityMode, "conversation_migration_count": record.ConversationMigrationCount},
		"runtime_revision": record.RuntimeRevision,
	}
	s.addReferencePricing(response["client_request"].(map[string]any), record)
	if trace != nil {
		response["required_capabilities"] = trace.RequiredCaps
		exclusions := []map[string]any{}
		seen := map[string]bool{}
		appendExclusion := func(targetID domain.ResourceTargetID, reason string) {
			key := string(targetID) + "\x00" + reason
			if seen[key] {
				return
			}
			seen[key] = true
			item := map[string]any{"reason": reason}
			if snap != nil {
				if target := snap.Targets[targetID]; target != nil {
					item["provider_id"] = target.ProviderID
					item["connection_id"] = target.ConnectionID
					item["upstream_model"] = target.Model
					egress := target.EgressProtocol(record.Protocol)
					item["upstream_capabilities"] = target.UpstreamCapabilitiesFor(egress)
					item["capabilities"] = target.CapabilitiesFor(egress)
				}
			}
			exclusions = append(exclusions, item)
		}
		for _, candidate := range trace.Candidates {
			if !candidate.Eligible {
				previous := len(exclusions)
				appendExclusion(candidate.Target, candidate.ExclusionReason)
				if len(exclusions) > previous {
					item := exclusions[len(exclusions)-1]
					item["capability_status"] = candidate.CapabilityStatuses
					item["capability_verification_error"] = candidate.CapabilityVerificationError
					item["capability_probe_requests"] = candidate.CapabilityProbeRequests
				}
			}
		}
		for _, exclusion := range record.Exclusions {
			appendExclusion(exclusion.Target, exclusion.Reason)
		}
		response["candidate_exclusions"] = exclusions
	}
	debugRecord, err := s.deps.Ledger.QueryRequestDebug(record.ID)
	if err != nil {
		writeMgmtErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	if debugRecord != nil {
		debug := map[string]any{
			"request_truncated":  debugRecord.RequestTruncated,
			"response_truncated": debugRecord.ResponseTruncated,
		}
		if json.Valid([]byte(debugRecord.RequestJSON)) {
			debug["request"] = json.RawMessage(debugRecord.RequestJSON)
		}
		if json.Valid([]byte(debugRecord.ResponseJSON)) {
			debug["response"] = json.RawMessage(debugRecord.ResponseJSON)
		}
		response["debug"] = debug
	}
	writeMgmtJSON(w, http.StatusOK, response)
}

