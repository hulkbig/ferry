type modelCatalogRoundTripFunc func(*http.Request) (*http.Response, error)

func (f modelCatalogRoundTripFunc) RoundTrip(request *http.Request) (*http.Response, error) {
	return f(request)
}

func modelCatalogResponse(status int, body string) *http.Response {
	return &http.Response{
		StatusCode: status, Header: make(http.Header),
		Body: io.NopCloser(strings.NewReader(body)),
	}
}

func configureCustomModelSyncFixture(f *v2APIFixture, transport http.RoundTripper, now time.Time) {
	f.server.deps.Resolver = &config.Resolver{Store: func(name string) (string, bool) {
		return "catalog-secret", name == "FERRY_V2_TEST_KEY"
	}}
	f.server.deps.ProviderModelHTTPClient = &http.Client{Transport: transport}
	f.server.deps.Now = func() time.Time { return now }
}

func TestProviderModelSyncAddsOnlyCatalogModelsAndIsIdempotent(t *testing.T) {
	f := newV2APIFixture(t)
	now := time.Date(2026, 9, 5, 10, 0, 0, 0, time.UTC)
	var requests atomic.Int64
	configureCustomModelSyncFixture(f, modelCatalogRoundTripFunc(func(request *http.Request) (*http.Response, error) {
		requests.Add(1)
		if request.Method != http.MethodGet || request.URL.String() != "https://example.test/v1/models" ||
			request.Header.Get("Authorization") != "Bearer catalog-secret" {
			t.Fatalf("catalog request=%s %s auth=%q", request.Method, request.URL, request.Header.Get("Authorization"))
		}
		return modelCatalogResponse(http.StatusOK, `{"data":[{"id":"upstream-model"},{"id":"new-model"}]}`), nil
	}), now)

	rec, response := f.do(http.MethodPost, "/api/providers/provider-a/models/sync", nil)
	requireStatus(t, rec, http.StatusOK)
	if response["status"] != "succeeded" || response["interval"] != "1h" ||
		response["discovered_models"] != float64(2) || response["added_models"] != float64(1) ||
		response["created_logical_models"] != float64(1) || response["added_model_count"] != float64(1) {
		t.Fatalf("sync response=%v", response)
	}
	if ids, ok := response["added_model_ids"].([]any); !ok || len(ids) != 1 || ids[0] != "new-model" {
		t.Fatalf("added ids=%v", response["added_model_ids"])
	}
	if next, _ := response["next_run_at"].(string); next != now.Add(time.Hour).Format(time.RFC3339) {
		t.Fatalf("next_run_at=%v", response["next_run_at"])
	}

	active, revision, err := f.control.ActiveConfig()
	if err != nil {
		t.Fatal(err)
	}
	connection := providerConnection(active, "provider-a", "connection-a")
	if connection == nil || len(connection.Models) != 3 {
		t.Fatalf("models=%+v", connection)
	}
	if logicalAt := logicalModelIndex(active, "new-model"); logicalAt < 0 ||
		!active.LogicalModels[logicalAt].AutoGenerated ||
		active.LogicalModels[logicalAt].DefaultRoute.Steps[0].ProviderID != "provider-a" {
		t.Fatalf("new logical model=%+v", active.LogicalModels)
	}
	if smartAt := logicalModelIndex(active, "smart"); smartAt < 0 || active.LogicalModels[smartAt].AutoGenerated ||
		active.LogicalModels[smartAt].DefaultRoute.Steps[0].UpstreamModel != "upstream-model" {
		t.Fatalf("custom route changed=%+v", active.LogicalModels)
	}

	repeatRec, repeat := f.do(http.MethodPost, "/api/providers/provider-a/models/sync", nil)
	requireStatus(t, repeatRec, http.StatusOK)
	if repeat["added_models"] != float64(0) || repeat["created_logical_models"] != float64(0) {
		t.Fatalf("repeat response=%v", repeat)
	}
	_, repeatedRevision, err := f.control.ActiveConfig()
	if err != nil {
		t.Fatal(err)
	}
	if repeatedRevision != revision || requests.Load() != 2 {
		t.Fatalf("repeat revision=%d want=%d requests=%d", repeatedRevision, revision, requests.Load())
	}

	providerRec, providerView := f.do(http.MethodGet, "/api/providers/provider-a", nil)
	requireStatus(t, providerRec, http.StatusOK)
	modelSync, ok := providerView["model_sync"].(map[string]any)
	if providerView["model_sync_interval"] != "1h" || !ok || modelSync["status"] != "succeeded" ||
		modelSync["added_models"] != float64(0) || modelSync["last_success_at"] == nil {
		t.Fatalf("provider view=%v", providerView)
	}
}

